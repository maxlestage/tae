impl Ui {
    /// « Corsé · 4/5 »
    pub fn intensity_name(&self, level: u8) -> String {
        let i = usize::from(level.clamp(1, 5)) - 1;
        format!("{} · {level}/5", self.intensity_names[i])
    }

    pub fn footer(&self, count: usize, year: u32) -> String {
        format!(
            "© {year} {} Maxime Nathan Lestage · @maxlestage · {count} {}",
            self.footer_by, self.footer_teas
        )
    }

    pub fn open_aria(&self, name: &str) -> String {
        format!("{} {name}", self.open_aria)
    }
}

pub fn ui(lang: Lang) -> &'static Ui {
    match lang {
        Lang::Fr => &FR,
        Lang::En => &EN,
        Lang::Es => &ES,
    }
}

